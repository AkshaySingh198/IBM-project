import io
import csv
from typing import List
from fpdf import FPDF
from app.models.schema_models import AuditLog

def generate_csv_report(logs: List[AuditLog]) -> str:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "ID", "Timestamp (ISO)", "Actor ID", "Action Type", "Target ID", "Previous Hash", "Current Hash"
    ])
    for log in logs:
        writer.writerow([
            log.id,
            log.created_at,
            log.actor_id,
            log.action_type,
            log.target_id or "",
            log.prev_hash,
            log.hash
        ])
    return output.getvalue()

def generate_pdf_report(logs: List[AuditLog]) -> bytes:
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    
    # Header
    pdf.cell(0, 10, "Privacy-Preserving Fraud Governance - Audit Trail Report", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 8, "Generated by Governance & Compliance Infra Engine", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)
    
    # Table Header
    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(20, 8, "Log ID", 1)
    pdf.cell(35, 8, "Timestamp", 1)
    pdf.cell(35, 8, "Actor ID", 1)
    pdf.cell(30, 8, "Action Type", 1)
    pdf.cell(20, 8, "Target ID", 1)
    pdf.cell(50, 8, "SHA-256 Hash", 1)
    pdf.ln()
    
    pdf.set_font("Helvetica", "", 7)
    for log in logs:
        ts_short = log.created_at.split("T")[0] + " " + log.created_at.split("T")[1][:5] if "T" in log.created_at else log.created_at[:16]
        hash_trunc = log.hash[:16] + "..." if log.hash else ""
        
        pdf.cell(20, 6, str(log.id), 1)
        pdf.cell(35, 6, ts_short, 1)
        pdf.cell(35, 6, str(log.actor_id), 1)
        pdf.cell(30, 6, str(log.action_type), 1)
        pdf.cell(20, 6, str(log.target_id or "-"), 1)
        pdf.cell(50, 6, hash_trunc, 1)
        pdf.ln()
        
    return bytes(pdf.output())
